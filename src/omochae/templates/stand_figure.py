# 形（姿）から出典を選ぶ表。--source を省いた時の既定と、合わない出典を落とす検査（compose の F1.source）が使う。
SOURCES = {k: f["source"] for k, f in FIGURES.items()}


def figure_defaults(figure):
    """その姿の既定: 共通の出発点に、姿に勧める立て方と寸法を重ねた物。"""
    f = FIGURES[figure]
    return {**BASE_DEFAULTS, "stand": f["stand"], **f.get("suggest", {})}


def filled(p):
    """None（＝姿の勧め）の値を、その姿の既定で埋める。書いた値はそのまま勝つ。姿が一覧に無ければ埋めない（範囲の検査が落とす）。"""
    if p.get("figure") not in FIGURES:
        return dict(p)
    base = figure_defaults(p["figure"])
    return {**p, **{k: base[k] for k in base if p.get(k) is None}}


def _filling(fn):
    """外から p を受ける関数の入口で filled を通す。中の関数どうしで呼んでも、もう埋まっているので変わらない。"""
    @wraps(fn)
    def run(p, *a):
        return fn(filled(p), *a)
    return run


@_filling
def title(p):
    return f"{FIGURES[p['figure']]['title']}・{'脚で立てる' if p['stand'] == 'easel' else '箱の台に差す'}"


def spec():
    # 姿ごとの既定も見せる（立て方と寸法は姿で変わる。None の既定だけでは何で刷られるか分からない）。
    return {"template_id": ID, "defaults": DEFAULTS, "ranges": RANGES, "figure": FORMS, "stand": STANDS, "back": (0, 1),
            "figures": {k: figure_defaults(k) for k in FIGURES}}


@_filling
def check_range(p):
    out = []
    for k, v in p.items():
        if k == "figure":
            if v not in FIGURES:
                out.append(Failure("F5.range", k, f"{v} は姿の一覧（{len(FIGURES)} 個）に無い"))
        elif k == "stand":
            if v not in STANDS:
                out.append(Failure("F5.range", k, f"{v} は {STANDS} のどれでもない"))
        elif k == "back":
            # 0 か 1 だけ。0.5 のような値は「半分刷る」にならないので落とす。
            if v not in (0, 1) or isinstance(v, bool):
                out.append(Failure("F5.range", k, f"{v} は 0 か 1 でない"))
        elif k not in RANGES:
            out.append(Failure("F5.range", k, "知らない寸法の名前"))
        elif v is None:
            continue  # 姿が一覧に無くて埋まらなかった既定。姿の名の誤りとして上で 1 つだけ落とす
        elif not isinstance(v, (int, float)) or isinstance(v, bool) or not RANGES[k][0] <= v <= RANGES[k][1]:
            out.append(Failure("F5.range", k, f"{v} は範囲 {RANGES[k]} の外"))
    return out


def _turn(f):
    """図の点を、姿を立てる向きに回す関数。図で斜めに描かれた物（弓・竿など）は、"axis" の下の点から上の点が真上を向くよう回す。"""
    if "axis" not in f:
        return lambda pts: list(pts)
    (bx, by), (tx, ty) = f["axis"]
    t = math.atan2(-1, 0) - math.atan2(ty - by, tx - bx)
    c, n = math.cos(t), math.sin(t)
    return lambda pts: [(bx + (x - bx) * c - (y - by) * n, by + (x - bx) * n + (y - by) * c) for x, y in pts]


# 高さは連続の値なので、上限を置く（場面を回し続けても覚えが増え続けないように）。1 枚の型紙で使う高さは 1 つ。
@lru_cache(maxsize=64)
def _shape(figure, height):
    """姿の外形（mm・左上が原点・下の縁が y = height）と、絵（姿の中に切った物）。玩具と高さが同じなら毎回同じなので覚えておく。
    "clip" のある姿は、回した後の下の端をその割合だけ切り落として、床に触れる平らな縁を作る（尖った下の端では立たない）。"""
    f = FIGURES[figure]
    turn = _turn(f)
    raw = unary_union([Polygon(turn(b)).buffer(0) for b in f["body"]])
    x0, y0, x1, y1 = raw.bounds
    if f.get("clip"):
        y1 -= f["clip"] * (y1 - y0)
        raw = raw.intersection(box(x0 - 1, y0 - 1, x1 + 1, y1))
    s = height / (y1 - y0)

    def tr(pts):
        return [((x - x0) * s, (y - y0) * s) for x, y in turn(pts)]

    body = raw if raw.geom_type == "Polygon" else None
    if body is None:
        # 外形がつながっていないと 1 枚に切れない。データの誤りなので、雛形の試験で見つける。
        raise ValueError(f"姿 {figure} の外形が 1 つにつながっていない")
    body = orient(Polygon([((x - x0) * s, (y - y0) * s) for x, y in body.exterior.coords]), sign=1.0)
    art = []
    inner = body.buffer(-0.15)
    for a in f["art"]:
        pts = tr(a["pts"])
        if a["kind"] == "poly":
            g = Polygon(pts).buffer(0).intersection(inner)
            for piece in getattr(g, "geoms", [g]):
                if piece.geom_type == "Polygon" and piece.area > 0.05:
                    art.append({"kind": "poly", "pts": list(piece.exterior.coords)[:-1], "fill": a["color"]})
        else:
            g = LineString(pts).intersection(inner.buffer(-a["sw"] / 2))
            for piece in getattr(g, "geoms", [g]):
                if piece.geom_type == "LineString" and piece.length > 0.3:
                    art.append({"kind": "line", "pts": list(piece.coords), "stroke": a["color"], "sw": a["sw"]})
    return body, art


@_filling
def figure_height(p):
    return FIGURES[p["figure"]]["height"] * p["scale"]


@_filling
def geometry(p):
    """姿の外形・重心・床に触れる所。式と型紙が同じ形を使うよう、ここ 1 つから出す。"""
    H = figure_height(p)
    body, art = _shape(p["figure"], round(H, 6))
    c = body.centroid
    cut = body.intersection(LineString([(-1, H - CONTACT_UP), (body.bounds[2] + 1, H - CONTACT_UP)]))
    contacts = sorted((min(x for x, _ in g.coords), max(x for x, _ in g.coords)) for g in getattr(cut, "geoms", [cut])
                      if g.geom_type == "LineString" and g.length > 0)
    return {"body": body, "art": art, "H": H, "W": body.bounds[2], "cx": c.x, "zc": H - c.y, "contacts": contacts}


def margin(g, above=0.0):
    """余白。above は傾きの軸から姿の下の縁までの高さ（台では箱の高さ。重心の高さはそこから測る）。"""
    return max(MIN_MARGIN, (g["zc"] + above) * math.tan(math.radians(TILT_TOL)))


@_filling
def easel(p):
    """脚の三角（前提は module の docstring）。付け根の高さ s と、足の形の奥行き c と、重心の奥行き。"""
    phi = math.radians(90 - LEAN_DEG)
    a, L = math.radians(p["tab_angle"]), p["tab_length"]
    g = geometry(p)
    return {"s": L * math.sin(a + phi) / math.sin(phi), "c": L * math.sin(a) / math.sin(phi),
            "com": g["zc"] * math.sin(math.radians(LEAN_DEG))}


@_filling
def tongue(p):
    """台に差す舌の位置と大きさ: (中心の x, 幅, 長さ)。重心に一番近い床に触れる所の上に置く（重心の真下で差すと台が小さくて済む）。"""
    g = geometry(p)
    w = p["slot_length"] - 2 * SLOT_END
    cx = g["cx"]
    # 床に触れる所ごとに、付け根が TONGUE_ATTACH 以上つながる舌の中心の範囲を出し、重心に一番近い所に置く。
    # 重心の側へ寄せるのは、重心が舌と床に触れる所の幅の外にあると、重さが舌の付け根をねじるため。
    best = None
    for a, b in g["contacts"]:
        k = TONGUE_ATTACH * w
        lo, hi = (a + k - w / 2, b - k + w / 2) if b - a >= k else ((a + b) / 2, (a + b) / 2)
        x = min(max(cx, lo), hi)
        if best is None or abs(x - cx) < abs(best - cx):
            best = x
    # 舌は箱の高さと同じ長さ: 上の溝と底の溝を通り、先が机に着く（2 つの高さで挟む前提）。
    return best, w, p["base_height"]


@_filling
def layers(p):
    return 2 if p["back"] else 1


@_filling
def wobble_deg(p):
    """溝の隙間で姿が傾ける角度。隙間が無い（差せない）時は None。"""
    gap = p["slot_width"] - layers(p) * p["paper_thickness"]
    if gap < MIN_CLEAR:
        return None
    # 2 つの溝は上の面と底の面の紙の真ん中にあり、その間は 箱の高さ − 紙の厚み。
    return math.degrees(math.atan(gap / (p["base_height"] - p["paper_thickness"])))


@_filling
def check_physics(p):
    """F5.stand: 姿が倒れない（重心が足の形の内に余白つきで入る）・脚が背に貼れる・溝が紙に合う、を見る。"""
    out = []
    g = geometry(p)
    m = margin(g)
    cx, H = g["cx"], g["H"]
    if p["stand"] == "easel":
        e = easel(p)
        tw = p["tab_width"]
        # 脚の糊代は姿の背の、重心の真後ろに貼る。糊代が姿の外にはみ出すと貼れない。
        patch = box(cx - tw / 2, H - e["s"] - p["tab_glue"], cx + tw / 2, H - e["s"])
        if not g["body"].buffer(-0.5).contains(patch):
            out.append(Failure("F5.stand", "脚", f"脚の糊代（付け根の高さ {e['s']:.0f}mm から上へ {p['tab_glue']:g}mm）が姿の背に収まらない"))
        foot = [(a, 0) for ab in g["contacts"] for a in ab] + [(cx - tw / 2, e["c"]), (cx + tw / 2, e["c"])]
        hull = Polygon(foot).convex_hull if len(foot) >= 3 else None
        com = Point(cx, e["com"])
        if hull is None or hull.geom_type != "Polygon" or not hull.buffer(-m).contains(com):
            if e["c"] - e["com"] < m:
                why = f"脚の足の形の奥行き {e['c']:.1f}mm が浅く、重心（下の縁から {e['com']:.1f}mm 後ろ）が後ろへ倒れる（余白 {m:.1f}mm 要る）"
            else:
                why = f"重心が足の形の横の端に近く、横へ倒れる（余白 {m:.1f}mm 要る）"
            out.append(Failure("F5.stand", "脚", why))
    else:
        x, w, depth = tongue(p)
        wob = wobble_deg(p)
        thick = layers(p) * p["paper_thickness"]
        if wob is None:
            out.append(Failure("F5.stand", "溝", f"溝の幅 {p['slot_width']:g}mm に紙 {thick:.2f}mm が入らない（隙間 {MIN_CLEAR}mm 以上）"))
        elif wob > MAX_WOBBLE:
            out.append(Failure("F5.stand", "溝", f"溝が緩く、姿が {wob:.1f}° ぐらつく（{MAX_WOBBLE}° まで）"))
        if p["slot_length"] > p["base_length"] - 2 * SLOT_EDGE:
            out.append(Failure("F5.stand", "溝", f"溝の端から箱の縁まで {SLOT_EDGE}mm 取れない"))
        edge = LineString([(x - w / 2, H - CONTACT_UP), (x + w / 2, H - CONTACT_UP)]).intersection(g["body"]).length
        if edge < TONGUE_ATTACH * w:
            out.append(Failure("F5.stand", "舌", f"差し込みの舌が姿と {edge:.1f}mm しかつながらず、差すと折れる（溝を短く）"))
        # 傾く軸は舌の先（机の上）なので、重心の高さは箱の高さを足して測る。余白も同じ高さから。
        hb = p["base_height"]
        mb = margin(g, hb)
        lean = (g["zc"] + hb) * math.tan(math.radians(wob or 0))
        foot = box(x - p["base_length"] / 2, -p["base_depth"] / 2, x + p["base_length"] / 2, p["base_depth"] / 2)
        if not foot.buffer(-mb).contains(Point(cx, lean)):
            out.append(Failure("F5.stand", "台", f"重心が台の縁に近く、倒れる（重心は舌から横へ {cx - x:.1f}mm・奥へ {lean:.1f}mm、余白 {mb:.1f}mm 要る）"))
        lo = min([a for a, _ in g["contacts"]] + [x - w / 2])
        hi = max([b for _, b in g["contacts"]] + [x + w / 2])
        if not lo <= cx <= hi:
            out.append(Failure("F5.stand", "舌", f"重心（左の端から {cx:.1f}mm）が床に触れる所と舌の幅（{lo:.1f}〜{hi:.1f}mm）の外で、舌の付け根がねじれる"))
    return out


def _mirror(pts, W):
    return [(W - x, y) for x, y in pts]


def _figure_part(number, key, name, p, mirror):
    p = filled(p)
    g = geometry(p)
    W, H = g["W"], g["H"]
    shape = g["body"]
    if p["stand"] == "base":
        x, w, depth = tongue(p)
        # 舌は姿の下の縁から少し上で重ねて足す。重ねないと、接するだけで 1 つの形にならない。
        joined = unary_union([shape, box(x - w / 2, H - CONTACT_UP, x + w / 2, H + depth)])
        if joined.geom_type == "Polygon":
            shape = orient(Polygon(joined.exterior.coords), sign=1.0)
    outline = list(shape.exterior.coords)[:-1]
    art = [{"kind": "poly", "pts": list(g["body"].buffer(-0.1).exterior.coords)[:-1], "fill": FIGURES[p["figure"]]["fill"]}]
    art += [dict(a) for a in g["art"]]
    if mirror:
        outline = _mirror(outline, W)
        for a in art:
            a["pts"] = _mirror(a["pts"], W)
        if p["stand"] == "easel":
            # 脚の糊代を貼る所の印（裏の背の上）。貼る高さを測らずに済むように。
            e = easel(p)
            tw, cx = p["tab_width"], W - g["cx"]
            y0, y1 = H - e["s"] - p["tab_glue"], H - e["s"]
            # 糊代が背に収まらない寸法（F5.stand で落ちる）でも、印は姿の中だけに描く（絵の検査が別の理由で重ねて落ちないように）。
            mark = LineString([(cx - tw / 2, y0), (cx + tw / 2, y0), (cx + tw / 2, y1), (cx - tw / 2, y1), (cx - tw / 2, y0)])
            mark = mark.intersection(Polygon(outline).buffer(-0.5))
            for piece in getattr(mark, "geoms", [mark]):
                if piece.geom_type == "LineString" and piece.length > 0.3:
                    art.append({"kind": "line", "pts": list(piece.coords), "stroke": INK, "sw": 0.3})
    # 番号は姿の一番太い所（輪郭から一番遠い点）に置く。重心だと、曲がった姿（犬の腹の下など）で外へ出る。
    c = polylabel(g["body"], tolerance=0.5)
    lx = (W - c.x if mirror else c.x) - 1
    return Part(number, key, name, outline, label_xy=(lx, c.y - 1.8), label=str(number), art=art)


GAUGE_W, GAUGE_END = 8, 4  # 開きの物差しの幅と、印の外の持ち手の長さ


@_filling
def _gauge(p):
    """開きの物差し: 上の印を姿の下の縁に当て、下の印に脚の先を置くと、開きが式の c になる。"""
    c = easel(p)["c"]
    L = c + 2 * GAUGE_END
    part = Part(4, "gauge", "開きの物差し", [(0, 0), (GAUGE_W, 0), (GAUGE_W, L), (0, L)], label_xy=(1, GAUGE_END + c / 2 - 1.8), label="4")
    part.art = [{"kind": "poly", "pts": [(0.2, 0.2), (GAUGE_W - 0.2, 0.2), (GAUGE_W - 0.2, L - 0.2), (0.2, L - 0.2)], "fill": PAPER}]
    part.art += [{"kind": "line", "pts": [(0.3, y), (GAUGE_W - 0.3, y)], "stroke": INK, "sw": 0.4} for y in (GAUGE_END, GAUGE_END + c)]
    return part


@_filling
def _tab(p):
    tw, L, gl = p["tab_width"], p["tab_length"], p["tab_glue"]
    part = Part(3, "tab", "脚", [(0, 0), (tw, 0), (tw, gl + L), (0, gl + L)], label_xy=(1, gl + 2), label="3 脚")
    part.valley = [((0, gl), (tw, gl))]
    part.glue = [[(0, 0), (tw, 0), (tw, gl), (0, gl)]]
    part.art = [{"kind": "poly", "pts": [(0.2, gl + 0.2), (tw - 0.2, gl + 0.2), (tw - 0.2, gl + L - 0.2), (0.2, gl + L - 0.2)], "fill": STAND_FILL}]
    return part


@_filling
def base_net(p):
    """台の箱の展開図: 上の面・後ろの壁・底・前の壁を縦に、左右の壁を底の横に。上の面に溝を切る。
    上の面は後ろの壁から倒して閉じ、前の糊代と左右の糊代を壁の内に貼る。左右の壁の糊代は前後の壁の内に貼る。"""
    L, D, Hb, g = p["base_length"], p["base_depth"], p["base_height"], p["base_glue"]
    f = min(g, Hb - 1)  # 上の面の左右の糊代は壁の高さより短く（底に当たらない）
    X0, X1, X2, X3 = 0, Hb, Hb + L, 2 * Hb + L
    Y1 = g
    Y2, Y3 = Y1 + D, Y1 + D + Hb
    Y4, Y5 = Y3 + D, Y3 + D + Hb
    glue = [[(X1 + 2, 0), (X2 - 2, 0), (X2, Y1), (X1, Y1)],
            [(X1 - f, Y1 + 2), (X1, Y1), (X1, Y2), (X1 - f, Y2 - 2)], [(X2, Y1), (X2 + f, Y1 + 2), (X2 + f, Y2 - 2), (X2, Y2)],
            [(X0 + 0.5, Y3), (X0 + 2, Y3 - g), (X1 - 2, Y3 - g), (X1 - 0.5, Y3)], [(X2 + 0.5, Y3), (X2 + 2, Y3 - g), (X3 - 2, Y3 - g), (X3 - 0.5, Y3)],
            [(X0 + 0.5, Y4), (X1 - 0.5, Y4), (X1 - 2, Y4 + g), (X0 + 2, Y4 + g)], [(X2 + 0.5, Y4), (X3 - 0.5, Y4), (X3 - 2, Y4 + g), (X2 + 2, Y4 + g)]]
    faces = [box(X1, Y1, X2, Y5), box(X0, Y3, X3, Y4)]
    net = unary_union(faces + [Polygon(q) for q in glue])
    outline = list(orient(Polygon(net.exterior.coords), sign=1.0).exterior.coords)[:-1]
    part = Part(3, "base", "台の箱", outline, label_xy=(X1 + 2, Y2 + 1.5), label="3 台")
    part.valley = [((X1, Y1), (X2, Y1)), ((X1, Y2), (X2, Y2)), ((X1, Y3), (X2, Y3)), ((X1, Y4), (X2, Y4)),
                   ((X1, Y1), (X1, Y2)), ((X2, Y1), (X2, Y2)), ((X1, Y3), (X1, Y4)), ((X2, Y3), (X2, Y4)),
                   ((X0, Y3), (X1, Y3)), ((X2, Y3), (X3, Y3)), ((X0, Y4), (X1, Y4)), ((X2, Y4), (X3, Y4))]
    part.glue = glue
    sl, sw = p["slot_length"], p["slot_width"]
    # 上の面と底の面の真ん中に同じ溝。上の面は後ろの壁から倒して閉じるので、どちらも面の真ん中なら閉じた時に上下にそろう。
    part.cuts = [(X1 + L / 2 - sl / 2, Y1 + D / 2 - sw / 2, sl, sw), (X1 + L / 2 - sl / 2, Y3 + D / 2 - sw / 2, sl, sw)]
    panel = lambda a, b, c, d: {"kind": "poly", "pts": [(a + 0.2, b + 0.2), (c - 0.2, b + 0.2), (c - 0.2, d - 0.2), (a + 0.2, d - 0.2)], "fill": STAND_FILL}
    part.art = [panel(X1, Y1, X2, Y2), panel(X1, Y2, X2, Y3), panel(X1, Y4, X2, Y5), panel(X0, Y3, X1, Y4), panel(X2, Y3, X3, Y4)]
    return part


@_filling
def parts(p):
    out = [_figure_part(1, "front", "表の姿", p, False)]
    if p["back"]:
        out.append(_figure_part(2, "back", "裏の姿", p, True))
    out += [_tab(p), _gauge(p)] if p["stand"] == "easel" else [base_net(p)]
    return out


def place(by_key, page, top, gap):
    """表・裏・立てる部品を、左から右へ、入らなければ次の段へ並べる。
    説明の列は最後の段の右に置く。物差し（100mm）が入らない時は、全部の部品の下に置く。"""
    x, y, row_h, right = page.x0, top, 0, page.x0
    for key in ("front", "back", "tab", "gauge", "base"):
        if key not in by_key:
            continue
        q = by_key[key]
        if x > page.x0 and x + q.width > page.x1:
            x, y, row_h = page.x0, y + row_h + gap, 0
        # 舌が姿の左の端より外へ出る物（細い棒の下の舌）は、外形が原点より左に出る。外形の左上を置き場に合わせる。
        q.x, q.y = x - min(a for a, _ in q.outline), y - min(b for _, b in q.outline)
        x += q.width + gap
        row_h = max(row_h, q.height)
    bottom = y + row_h
    if page.x1 - x >= 102:
        return y, page.x1 - x, x
    return bottom + gap, page.x1 - page.x0, page.x0


